import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { createReadStream } from "node:fs";
import { mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { Readable } from "node:stream";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { attachmentPython } from "../agent/attachments/parser.ts";
import { createAttachmentStore } from "../agent/attachments/store.ts";
import { createAttachmentTools } from "../agent/attachments/tools.ts";

test("大型 Excel 完整保留跨表超过二十万行，分页与精确计算覆盖落盘全表", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "ctf-large-xlsx-"));
  const fixtures = join(directory, "fixtures");
  const generated = spawnSync(attachmentPython(), ["tests/helpers/large-xlsx.py", fixtures], { encoding: "utf8", timeout: 30000 });
  assert.equal(generated.status, 0, generated.stderr);
  const store = createAttachmentStore({ directory: join(directory, "private") });
  t.after(async () => { await store.close(); await rm(directory, { recursive: true, force: true }); });
  const scope = { owner: crypto.randomUUID(), conversationId: crypto.randomUUID() };
  const upload = async (name: string) => {
    const initial = await store.upload(scope, { name, body: createReadStream(join(fixtures, name)) });
    await store.prepare(scope, [initial.id]).catch(() => {});
    return store.get(scope, initial.id);
  };
  const item = await upload("大表.xlsx");
  assert.equal(item.status, "ready", item.error);
  const retried = await store.retry(scope, item.id);
  assert.equal(retried.id, item.id); assert.equal(retried.status, "ready", "已读来源不能被重试覆盖");
  const tools = createAttachmentTools(store, scope, [item.id]);
  const [file] = await tools.list();
  assert.deepEqual(file.tables.map((table) => table.rows), [110000, 110000]);
  const table = file.tables[0];
  const tail = await tools.read({ attachmentId: item.id, tableId: table.id, offset: 109999 });
  assert.ok("rows" in tail && tail.rows);
  assert.deepEqual(tail.rows.map((row) => [row.rowNumber, row.values]), [[110001, ["110000", null, "华东"]]]);
  const sum = await tools.calculate({ attachmentId: item.id, tableId: table.id, operation: "sum", column: "金额" });
  assert.ok("value" in sum);
  assert.equal(sum.value, "10999.9"); assert.equal(sum.matchedRows, 110000); assert.equal(sum.missingRows, 1);
  const parsed = join(directory, "private", scope.owner, scope.conversationId, item.id, "parsed");
  assert.ok((await stat(join(parsed, "parsed.json"))).size < 100000, "目录文件不应内嵌整张大表");
  assert.ok((await stat(join(parsed, "tables.sqlite"))).size > 100000);
  await assert.rejects(store.document({ ...scope, owner: crypto.randomUUID() }, item.id), /不存在|无权/);

  const semantic = await upload("语义.xlsx");
  const diagnostic = await readFile(join(directory, "private", scope.owner, scope.conversationId, semantic.id, "parsed/parser-details.txt"), "utf8").catch(() => "");
  assert.equal(semantic.status, "partial", `${semantic.error ?? ""} ${diagnostic}`);
  const semanticTools = createAttachmentTools(store, scope, [semantic.id]);
  const [semantics] = await semanticTools.list();
  assert.equal(semantics.tables.length, 5, semantic.warnings.join("；"));
  const rows = await semanticTools.read({ attachmentId: semantic.id, tableId: semantics.tables[0].id });
  assert.ok("rows" in rows && rows.rows);
  assert.equal(rows.rows[0].values[2], "2026-10-16T00:00:00");
  assert.equal(rows.rows[0].values[3], null);
  assert.match(semantic.warnings.join("；"), /公式|缓存/);
  const merged = await semanticTools.calculate({ attachmentId: semantic.id, tableId: semantics.tables[0].id, operation: "sum", column: "金额", filters: [{ column: "地区", operator: "equals", value: "华东" }] });
  assert.ok("value" in merged); assert.equal(merged.value, "0.3");
  await assert.rejects(semanticTools.calculate({ attachmentId: semantic.id, tableId: semantics.tables[1].id, operation: "sum", column: "金额" }), /合并|歧义/);
  assert.equal(semantics.tables[2].columns.length, 4);
  const omitted = await semanticTools.read({ attachmentId: semantic.id, tableId: semantics.tables[3].id });
  assert.ok("rows" in omitted && omitted.rows); assert.equal(omitted.rows[0].rowNumber, 3);
  const escaped = await semanticTools.read({ attachmentId: semantic.id, tableId: semantics.tables[4].id });
  assert.ok("rows" in escaped && escaped.rows); assert.deepEqual(escaped.rows.map((row) => row.values[0]), ["_x000D_", "_x005F_x0041_"]);
  const oversize = await upload("超大内部项.xlsx");
  assert.equal(oversize.status, "failed"); assert.match(oversize.error ?? "", /限额/);
});

test("旧失败解析重试创建新版本附件，旧来源与原件保持不变", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "ctf-xlsx-version-"));
  const store = createAttachmentStore({ directory });
  t.after(async () => { await store.close(); await rm(directory, { recursive: true, force: true }); });
  const scope = { owner: crypto.randomUUID(), conversationId: crypto.randomUUID() };
  const original = await store.upload(scope, { name: "销售.csv", body: Readable.from([Buffer.from("门店,金额\n甲,0.1\n")]) });
  await store.prepare(scope, [original.id]);
  const item = await store.get(scope, original.id);
  const legacy = { ...item, parserVersion: "attachments/1", version: createHash("sha256").update(`${item.contentHash}/attachments/1`).digest("hex"), status: "failed", error: "旧环境未完成解析" };
  const metadata = join(directory, scope.owner, scope.conversationId, item.id, "metadata.json");
  await writeFile(metadata, JSON.stringify(legacy));
  const current = await store.retry(scope, item.id);
  assert.notEqual(current.id, item.id); assert.equal(current.parserVersion, "attachments/4"); assert.notEqual(current.version, legacy.version); assert.equal(current.status, "uploaded");
  assert.deepEqual(await store.get(scope, item.id), legacy);
  await store.prepare(scope, [current.id]);
  assert.equal((await store.get(scope, current.id)).status, "ready");
});

test("中断的旧版解析任务不会在新程序中冒用旧版本自动续跑", async (t) => {
  const directory = await mkdtemp(join(tmpdir(), "ctf-xlsx-resume-"));
  let store = createAttachmentStore({ directory });
  t.after(async () => { await store.close(); await rm(directory, { recursive: true, force: true }); });
  const scope = { owner: crypto.randomUUID(), conversationId: crypto.randomUUID() };
  const item = await store.upload(scope, { name: "销售.csv", body: Readable.from([Buffer.from("门店,金额\n甲,0.1\n")]) });
  await store.prepare(scope, [item.id]);
  await store.close();
  const metadata = join(directory, scope.owner, scope.conversationId, item.id, "metadata.json");
  const legacy = { ...JSON.parse(await readFile(metadata, "utf8")), parserVersion: "attachments/1", status: "processing" };
  await writeFile(metadata, JSON.stringify(legacy));
  store = createAttachmentStore({ directory });
  const restored = await store.get(scope, item.id);
  assert.equal(restored.status, "failed"); assert.match(restored.error ?? "", /更新|重试/);
  assert.equal(restored.parserVersion, "attachments/1"); assert.equal(restored.version, legacy.version);
});
